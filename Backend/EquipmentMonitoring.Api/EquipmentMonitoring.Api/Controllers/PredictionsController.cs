using EquipmentMonitoring.Api.Entities;
using EquipmentMonitoring.Api.Models;
using EquipmentMonitoring.Api.Repositories;
using EquipmentMonitoring.Api.Services;
using Microsoft.AspNetCore.Mvc;
using System.Net;
using System.Net.Http.Json;

namespace EquipmentMonitoring.Api.Controllers
{
    [ApiController]
    [Route("api/[controller]")]
    public class PredictionsController : ControllerBase
    {
        private readonly IHttpClientFactory _httpClientFactory;
        private readonly EmailService _emailService;
        private readonly UserRepository _userRepository;
        private readonly EmailNotificationRepository _notificationRepository;

        public PredictionsController(
    IHttpClientFactory httpClientFactory,
    EmailService emailService,
    UserRepository userRepository,
    EmailNotificationRepository notificationRepository)
        {
            _httpClientFactory =
                httpClientFactory;

            _emailService =
                emailService;

            _userRepository =
                userRepository;

            _notificationRepository =
                notificationRepository;
        }

        [HttpPost]
        public async Task<IActionResult> Predict(
            [FromBody] PredictionRequest request)
        {
            if (string.IsNullOrWhiteSpace(request.Type))
            {
                return BadRequest(new
                {
                    message = "Equipment type is required."
                });
            }

            try
            {
                var client =
                    _httpClientFactory.CreateClient(
                        "MlService"
                    );

                var response =
                    await client.PostAsJsonAsync(
                        "/predict",
                        request
                    );

                if (response.IsSuccessStatusCode)
                {
                    var prediction =
                        await response.Content
                            .ReadFromJsonAsync
                            <PredictionResponse>();

                    if (prediction == null)
                    {
                        return StatusCode(
                            StatusCodes
                                .Status502BadGateway,
                            new
                            {
                                message =
                                    "The ML service returned an empty response."
                            }
                        );
                    }

                    if (
                        prediction.MaintenancePriority
                            .Equals(
                                "High",
                                StringComparison
                                    .OrdinalIgnoreCase
                            )
                    )
                    {
                        var recipients =
                            await _userRepository
                                .GetNotificationRecipientsAsync();

                        var emailBody =
$"""
<html>

<body style="
font-family: Arial, sans-serif;
background-color: #f5f7fa;
padding: 20px;">

<div style="
max-width: 700px;
background: white;
padding: 24px;
border-radius: 10px;
border: 1px solid #dcdcdc;">

<h2 style="
color:#dc2626;
margin-top:0;">

🚨 High Priority Equipment Alert

</h2>

<p>

A high-priority maintenance prediction
has been generated by the Equipment
Monitoring System.

</p>

<hr>

<table style="
width:100%;
border-collapse:collapse;">

<tr>
<td><strong>Equipment Type</strong></td>
<td>{request.Type}</td>
</tr>

<tr>
<td><strong>Failure Prediction</strong></td>
<td>{prediction.Prediction}</td>
</tr>

<tr>
<td><strong>Failure Probability</strong></td>
<td>{prediction.FailureProbability:P2}</td>
</tr>

<tr>
<td><strong>Maintenance Priority</strong></td>
<td>
<span style="
color:#dc2626;
font-weight:bold;">
{prediction.MaintenancePriority}
</span>
</td>
</tr>

<tr>
<td><strong>Model</strong></td>
<td>{prediction.Model}</td>
</tr>

</table>

<hr>

<p style="
color:#555;">

Immediate inspection and
maintenance action is recommended.

</p>

</div>

</body>

</html>
""";

                        foreach (
    var recipient
    in recipients
)
                        {
                            await _emailService
                                .SendEmailAsync(
                                    recipient.EmailAddress,
                                    "🚨 High Priority Equipment Alert",
                                    emailBody
                                );

                            await _notificationRepository
                                .SaveAsync(
                                    new EmailNotification
                                    {
                                        Recipient =
                                            recipient.Username,

                                        Subject =
                                            "🚨 High Priority Equipment Alert",

                                        Status =
                                            "Sent",

                                        DateSent =
                                            DateTime.UtcNow
                                    }
                                );
                        }
                    }

                    return Ok(prediction);
                }

                var error =
                    await response.Content
                        .ReadAsStringAsync();

                if (
                    response.StatusCode ==
                        HttpStatusCode.BadRequest
                    ||
                    response.StatusCode ==
                        HttpStatusCode
                            .UnprocessableEntity
                )
                {
                    return BadRequest(
                        new
                        {
                            message =
                                "Prediction input was rejected.",
                            mlServiceError =
                                error
                        }
                    );
                }

                return StatusCode(
                    StatusCodes
                        .Status502BadGateway,
                    new
                    {
                        message =
                            "The ML prediction service returned an error.",
                        mlServiceError =
                            error
                    }
                );
            }
            catch (HttpRequestException)
            {
                return StatusCode(
                    StatusCodes
                        .Status503ServiceUnavailable,
                    new
                    {
                        message =
                            "The ML prediction service is unavailable."
                    }
                );
            }
            catch (TaskCanceledException)
            {
                return StatusCode(
                    StatusCodes
                        .Status504GatewayTimeout,
                    new
                    {
                        message =
                            "The ML prediction service did not respond in time."
                    }
                );
            }
        }
    }
}